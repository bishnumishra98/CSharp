// ● In C#, data types are categorized into two main types: Value Types and Reference Types.

// ● Value Types: These types store the actual data directly in memory. When a value type is assigned to a new variable,
//                a copy of the value is created. Changes made to one variable do not affect the other.
//                - Examples of value types include int, float, double, char, bool, struct, enum, etc.

// ● Reference Types: These types store a reference (or address) to the actual data in memory. When a reference type is assigned
//                    to a new variable, both variables point to the same data in memory. Changes made to one variable affect the other.
//					  - Examples of reference types include string, class, array, delegate, etc.
